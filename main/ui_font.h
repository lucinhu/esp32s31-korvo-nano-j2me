static const uint8_t *glyph_rows(char ch)
{
    static const uint8_t missing[FONT_H] = { 0x1f, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1f };

    if (ch >= 'a' && ch <= 'z') {
        ch = (char)(ch - 'a' + 'A');
    }

    for (size_t i = 0; i < sizeof(s_font) / sizeof(s_font[0]); ++i) {
        if (s_font[i].ch == ch) {
            return s_font[i].rows;
        }
    }
    return missing;
}
